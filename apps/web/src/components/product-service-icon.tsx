const PALETTE = Object.keys(ICONS);

function hashKey(value: string): number {
  let hash = 0;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) >>> 0;
  }
  return hash;
}

function preferredIcon(slug?: string | null, iconKey?: string | null, name?: string | null): string {
  const slugKey = slug?.trim().toLowerCase() ?? '';
  if (slugKey && SLUG_ICONS[slugKey]) return SLUG_ICONS[slugKey];
  if (iconKey && ICONS[iconKey]) return iconKey;

  const hint = `${iconKey ?? ''} ${slugKey} ${name ?? ''}`.toLowerCase();
  for (const [pattern, key] of KEYWORD_ICONS) {
    if (pattern.test(hint)) return key;
  }

  return PALETTE[hashKey(slugKey || name || hint || 'product') % PALETTE.length];
}

export function uniqueIconKeys(items: Array<{ slug?: string | null; iconKey?: string | null; name?: string | null }>): string[] {
  const taken = new Set<string>();
  return items.map((item) => {
    const preferred = preferredIcon(item.slug, item.iconKey, item.name);
    let key = preferred;
    if (taken.has(key)) {
      key = PALETTE.find((candidate) => !taken.has(candidate)) ?? PALETTE[taken.size % PALETTE.length];
    }
    taken.add(key);
    return key;
  });
}

